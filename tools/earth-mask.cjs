// Bake Natural Earth land polygons into an equirectangular, least-significant-bit-first mask.
// Usage: node tools/earth-mask.cjs path/to/ne_110m_land.geojson
const fs = require('fs'), path = require('path');
if (!process.argv[2]) throw new Error('GeoJSON path is required');
const geo = JSON.parse(fs.readFileSync(process.argv[2], 'utf8'));
const rings = [];
for (const { geometry: g } of geo.features) {
  const polys = g.type === 'MultiPolygon' ? g.coordinates : [g.coordinates];
  for (const poly of polys) for (const ring of poly) rings.push(ring);
}
const w = 256, h = 128, bits = Buffer.alloc(w * h / 8);
for (let j = 0; j < h; j++) {
  const lat = 90 - (j + .5) * 180 / h, xs = [];
  for (const ring of rings) for (let k = 1; k < ring.length; k++) {
    const [x1, y1] = ring[k - 1], [x2, y2] = ring[k];
    if ((y1 > lat) !== (y2 > lat)) xs.push(x1 + (lat - y1) * (x2 - x1) / (y2 - y1));
  }
  xs.sort((a, b) => a - b);
  let n = 0;
  for (let i = 0; i < w; i++) {
    const lon = -180 + (i + .5) * 360 / w;
    while (n < xs.length && xs[n] < lon) n++;
    if (n % 2) { const k = j * w + i; bits[k >> 3] |= 1 << (k & 7); }
  }
}
fs.writeFileSync(path.join(__dirname, '../data/earth.js'), `// Natural Earth ne_110m_land, public domain: https://www.naturalearthdata.com/\n// Generated by tools/earth-mask.cjs; rows run north to south, bits least significant first.\nwindow.WOS_DATA.earthLand={w:${w},h:${h},bits:'${bits.toString('base64')}'};\n`);
